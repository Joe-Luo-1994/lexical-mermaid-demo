import assert from 'node:assert/strict';
import http from 'node:http';
import {mkdtemp, mkdir, writeFile, readFile, rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {existsSync} from 'node:fs';
import {chromium} from 'playwright';
import {initCase, runCase, queryCase} from './core.mjs';
import {serveCase} from './serve.mjs';

const temp = await mkdtemp(join(tmpdir(), 'agent-debug-viewer-'));
const project = join(temp, 'project'), caseDir = join(temp, 'case');
const out = new URL('../results/debug-core-viewer/', import.meta.url);
await mkdir(project); await mkdir(out, {recursive:true});
const checks = [], errors = [], external = [];
const check = (name, value) => {assert.ok(value, name); checks.push(name);};
let server, browser;
try {
  await writeFile(join(project, 'entry.js'), 'export const value = "<img src=x onerror=alert(1)>";\nexport function render() { return value; }\n');
  const adapter = `
    const fs = require('node:fs');
    const path = require('node:path');
    const start = performance.now();
    let checksum=0; for(let i=0;i<10000;i++) checksum+=Math.sqrt(i);
    const duration=performance.now()-start;
    const raw=[{id:'e1',name:'Measured node operation',startMs:start,durationMs:duration,source:{path:'entry.js',line:2}},{id:'e2',name:'Adjacent observation',startMs:start,durationMs:duration,source:{path:'entry.js',line:1}},{id:'e3',name:'Unmapped observation',startMs:start,durationMs:duration,source:null}];
    fs.writeFileSync(path.join(process.env.DEBUG_RUN_DIR,'raw.json'),JSON.stringify(raw));
    const capture={kind:'agent-debug-capture',version:1,runId:process.env.DEBUG_RUN_ID,clock:{unit:'ms',origin:'performance.timeOrigin',timeOrigin:performance.timeOrigin},events:raw.map((e,index)=>({...e,rawRef:{artifact:'raw.json',index}})),relations:[{from:'e1',to:'e2',type:'temporal-association',reason:'same times, no call evidence'}],coverage:{installed:['test fixture'],dropped:0,limitations:['Viewer integration test, not a Lexical diagnostic']},artifacts:['raw.json'],findings:[{id:'f1',status:'observed',text:'Operation captured; no root cause established',eventIds:['e1'],limitations:['No browser paint measurement']}],nextExperiment:{question:'Does the work contribute to delay?',intervention:'Change one workload',controls:['same input'],outcomes:['Reduced duration supports the explanation','Unchanged duration weakens it']},capabilities:{visibleResponse:'unverified',externalViewer:'unverified'},costs:{tokens:null,fee:null}};
    fs.writeFileSync(path.join(process.env.DEBUG_RUN_DIR,'capture.json'),JSON.stringify(capture));
  `;
  await writeFile(join(project, 'adapter.cjs'), adapter);
  const plan = join(temp, 'plan.json');
  await writeFile(plan, JSON.stringify({question:'Verify source/event navigation', outcomes:['Correctly locate one event','Reject stale or invalid data'],sources:['entry.js','adapter.cjs'],limitations:['Generated viewer integration fixture; not a diagnostic evaluation']}));
  await initCase({caseDir, projectRoot:project, operation:'Open a document: viewer integration check', budgetSeconds:1800});
  await runCase({caseDir, planPath:plan, command:[process.execPath,'adapter.cjs']});
  const summary = await queryCase(caseDir, {limit:20});
  const runId = summary.attempts.at(-1).id;
  server = await serveCase(caseDir);
  const base = `http://127.0.0.1:${server.address().port}`;
  check('server rejects mutation', (await fetch(base+'/api/case',{method:'POST'})).status===405);
  check('server rejects foreign origin', (await fetch(base+'/api/case',{headers:{Origin:'https://unrelated.example'}})).status===403);
  const foreignHostStatus = await new Promise((resolve,reject)=>{const req=http.get(base+'/api/case',{headers:{Host:'unrelated.example'}},res=>{res.resume();resolve(res.statusCode);});req.on('error',reject);});
  check('server rejects foreign host', foreignHostStatus===403);
  check('source path traversal rejected', (await fetch(base+'/api/source?'+new URLSearchParams({run:runId,path:'../outside'}))).status!==200);
  check('unknown event is not replaced by nearest', (await fetch(base+'/api/event?'+new URLSearchParams({run:runId,id:'missing'}))).status===404);
  browser = await chromium.launch({executablePath:process.env.BROWSER_PATH || (existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined),headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
  page.on('pageerror', e=>errors.push(String(e)));
  page.on('console', m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('request', r=>{if(!r.url().startsWith(base)&&!r.url().startsWith('blob:')&&!r.url().startsWith('data:'))external.push(r.url());});
  await page.goto(base);
  await page.locator('[data-event="e1"]').waitFor();
  check('full limitations start collapsed with visible capability gaps',!await page.locator('#limitations-disclosure').evaluate(e=>e.open) && (await page.locator('#capability-summary').innerText()).includes('100 ms'));
  await page.locator('#limitations-label').click();
  check('full limitations remain available through disclosure',await page.locator('#limitations').isVisible() && await page.locator('#limitations li').count()>0);
  await page.locator('#limitations-label').click();
  await page.getByRole('button',{name:'查看 e1',exact:true}).click();
  await page.locator('.source-line.target').waitFor();
  check('finding selects exact run/event', (await page.locator('#inspector').innerText()).includes(runId) && page.url().includes('event=e1'));
  check('source inspector highlights exact saved line', await page.locator('.source-line.target').getAttribute('data-line')==='2');
  check('source content rendered as text', await page.locator('#inspector img').count()===0 && (await page.locator('.source-lines').innerText()).includes('<img src=x'));
  check('no causal upgrade for same-time events', (await page.locator('.relations').innerText()).includes('temporal-association'));
  await page.locator('[data-event="e3"]').click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('沒有完成來源導航'));
  check('unmapped source is not announced as successful navigation',(await page.locator('#inspector').innerText()).includes('來源 unresolved') && await page.locator('.source-line.target').count()===0);
  await page.locator('[data-event="e1"]').click();
  await page.locator('.source-line.target').waitFor();
  await page.getByRole('button',{name:'返回事件列表',exact:true}).click();
  check('return restores event focus', await page.evaluate(()=>document.activeElement?.dataset.event)==='e1');
  await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.activeElement?.id==='inspector');
  check('keyboard opens inspector', await page.evaluate(()=>document.activeElement?.id)==='inspector');
  await page.screenshot({path:new URL('desktop.png',out).pathname,fullPage:true});
  await page.reload();
  await page.locator('.source-line.target').waitFor();
  check('deep link restores same event/source', await page.locator('.source-line.target').getAttribute('data-line')==='2');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'下載目前案例摘要',exact:true}).click();
  const download = await downloadPromise;
  await download.saveAs(new URL('handoff.json',out).pathname);
  const handoff = JSON.parse(await readFile(new URL('handoff.json',out),'utf8'));
  check('handoff retains case/deadline/limitations', handoff.summary.id===summary.id && handoff.summary.deadlineAt===summary.deadlineAt && handoff.selectedRun.limitations.length>0 && handoff.selectedEventId==='e1');
  await writeFile(join(project,'entry.js'),'// source changed\nexport const value=2;\n');
  await page.getByRole('button',{name:'重新查核案例',exact:true}).click();
  await page.getByText('歷史證據，來源已變更',{exact:true}).first().waitFor();
  check('stale source keeps historical snapshot', (await page.locator('.source-lines').innerText()).includes('<img src=x'));
  await page.setViewportSize({width:390,height:844});
  check('narrow viewport has no horizontal overflow', await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:new URL('mobile.png',out).pathname,fullPage:true});
  await writeFile(join(caseDir,'runs',runId,'raw.json'),'[]');
  await page.getByRole('button',{name:'重新查核案例',exact:true}).click();
  await page.getByText('完整性 檢查未通過',{exact:true}).waitFor();
  check('tampered run is not shown as evidence',await page.locator('[data-event]').count()===0 && (await page.locator('#limitations').innerText()).includes('integrity'));
  const failed = await runCase({caseDir,planPath:plan,command:[process.execPath,'-e','process.exit(2)']});
  await page.getByRole('button',{name:'重新查核案例',exact:true}).click();
  await page.waitForFunction(id=>Array.from(document.querySelector('#run-select').options).some(o=>o.value===id),failed.attempt.id);
  await page.selectOption('#run-select',failed.attempt.id);
  await page.getByText('執行失敗',{exact:true}).waitFor();
  check('failed attempt retained and readable',await page.locator('[data-event]').count()===0 && (await page.locator('#limitations').innerText()).includes('failed'));
  for(let i=0;i<19;i++)await runCase({caseDir,planPath:plan,command:[process.execPath,'-e','process.exit(2)']});
  await page.getByRole('button',{name:'重新查核案例',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#older').disabled);
  await page.getByRole('button',{name:'較舊嘗試',exact:true}).click();
  await page.waitForFunction(id=>Array.from(document.querySelector('#run-select').options).some(o=>o.value===id),runId);
  check('older attempts accessible through pagination',await page.locator('#newer').isEnabled() && await page.locator('#older').isDisabled());
  await page.route('**/api/case?*',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({kind:'agent-debug-query-too-large',error:'test response bound'})}));
  await page.getByRole('button',{name:'重新查核案例',exact:true}).click();
  await page.locator('#error').waitFor();
  check('oversize summary is explicit error not empty case',(await page.locator('#error').innerText()).includes('案例摘要無法完整取得') && await page.locator('#case-id').innerText()===summary.id);
  check('no external requests',external.length===0);
  check('no browser errors',errors.length===0);
  const result={kind:'debug-core-viewer-check',browser:browser.version(),checks,errors,externalRequests:external,scope:'real core case created by a generated Node fixture; no Lexical diagnosis or human usability claim',unverified:['external Perfetto/Chrome navigation','100 ms visible response','human usability']};
  await writeFile(new URL('browser-check.json',out),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result,null,2));
} finally {
  await browser?.close();
  if(server)await new Promise(resolve=>server.close(resolve));
  await rm(temp,{recursive:true,force:true});
}
